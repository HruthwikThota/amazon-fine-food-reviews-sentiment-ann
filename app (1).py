import re
import string
import joblib
import numpy as np
import streamlit as st
import tensorflow as tf


def clean_text(text):
  text = str(text).lower()
  text = re.sub(r"<.*?>", " ", text)
  text = re.sub(r"http\S+|www\S+", " ", text)
  text = text.translate(str.maketrans("", "", string.punctuation))
  text = re.sub(r"\s+", " ", text).strip()
  return text


def get_sentiment(rating):
  if rating >= 4:
    return "Positive"
  elif rating <= 2:
    return "Negative"
  else:
    return "Neutral"


@st.cache_resource
def load_artifacts():
  ann_model = tf.keras.models.load_model("final_ann_model.keras")
  tfidf_vec = joblib.load("tfidf_vectorizer.pkl")
  return ann_model, tfidf_vec


model, vectorizer = load_artifacts()

st.title("Amazon Review Sentiment Analysis (ANN)")
st.write(
    "Enter an Amazon product review below to predict its star rating (1–5) and"
    " sentiment."
)

review = st.text_area("Enter your review:")

if st.button("Predict"):
  if not review.strip():
    st.warning("Please enter a review.")
  else:
    cleaned = clean_text(review)
    features = vectorizer.transform([cleaned]).astype("float32").toarray()
    probs = model.predict(features, verbose=0)[0]

    predicted_rating = int(np.argmax(probs)) + 1
    confidence = float(np.max(probs))
    sentiment = get_sentiment(predicted_rating)

    st.subheader("Prediction Result")
    st.write("Predicted Rating:", predicted_rating)
    st.write("Sentiment:", sentiment)
    st.write("Confidence:", f"{confidence:.2%}")